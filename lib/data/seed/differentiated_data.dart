  static WorkoutExercise _slot({
    required String id,
    required String exerciseId,
    required int order,
    required String focus,
    required int restSeconds,
    required String restLabel,
    required int warmReps,
    required String warmNote,
    required int feedReps,
    required String feedNote,
    required int workSets,
    required int workMin,
    required int workMax,
    required String workNote,
    String repsUnit = 'reps',
  }) {
    return WorkoutExercise(
      id: id,
      exerciseId: exerciseId,
      order: order,
      focus: focus,
      restSeconds: restSeconds,
      restLabel: restLabel,
      sets: [
        SetPrescription(
          type: SetType.warmup,
          repMin: warmReps,
          repMax: warmReps,
          note: warmNote,
          repsUnit: repsUnit,
        ),
        SetPrescription(
          type: SetType.preparation,
          repMin: feedReps,
          repMax: feedReps,
          note: feedNote,
          repsUnit: repsUnit,
        ),
        for (var i = 0; i < workSets; i++)
          SetPrescription(
            type: SetType.working,
            repMin: workMin,
            repMax: workMax,
            note: workNote,
            repsUnit: repsUnit,
          ),
      ],
    );
  }

